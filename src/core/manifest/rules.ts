// The rule manifest (06, chapter 4): ids, defaults, CWE/OWASP, sources and option defaults of every
// built-in rule, as data. Config validation uses it without loading the rule code (01-AC-01); the
// rules in core/rules implement exactly these ids (contract test).
import type { Confidence, FindingScope, Severity, Source } from '../types/index.ts';

export type RuleGroup =
  'header' | 'cookie' | 'cors' | 'transport' | 'data' | 'disclosure' | 'browser';

export interface RuleManifest {
  id: string;
  group: RuleGroup;
  title: string;
  defaultSeverity: Severity;
  defaultConfidence: Confidence;
  scope: FindingScope;
  cwe: number[];
  /** OWASP Top 10 2025 category, e.g. 'A02:2025' (D-09). */
  owasp?: string;
  /** Traffic sources the rule applies to (15, chapter 5). */
  sources: Source[];
  /** Option defaults (03-REQ-03, P-13). */
  options: Record<string, unknown>;
  /** Only in the strict preset (Q-07). */
  strictOnly?: boolean;
}

