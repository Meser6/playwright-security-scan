// Static HTML report of one run (09, chapter 3.6): a pure function of the run report, the rule
// docs, the config and the tests of the run (09-REQ-18). The page is complete without JavaScript:
// all tab panels one below the other and the details of each finding in <details>; the embedded
// script adds tabs, filters, sorting, deep links and copying. Styles and script are build-time
// constants with their SHA-256 hashes for the Content-Security-Policy. Structure copied from
// playwright-performance-regression (src/html/render.ts, MIT, D-08).
import { context } from './context.ts';
import type { Ctx, HtmlReportInput } from './context.ts';
import { coverageTab, runTab } from './coverage.ts';
import { html, trustedHtml } from './escape.ts';
import type { HtmlValue, SafeHtml } from './escape.ts';
import { findingsTab } from './findings.ts';
import { formatDate, formatRunDuration } from './format.ts';
import { SCRIPT, SCRIPT_SHA256, STYLES, STYLES_SHA256 } from './generated/assets.ts';
import { FAVICON_URI, icon, iconSprite, logo } from './icons.ts';
import { kpis, verdictCard } from './overview.ts';
import { REPORTS_DOCS_URL, REPOSITORY_URL, badge, join } from './parts.ts';

export const PACKAGE_NAME = 'playwright-security-scan';

/** Tabs in their order (09-REQ-17, item 4). */
export type TabId = 'findings' | 'coverage' | 'run';

interface Tab {
  id: TabId;
  label: string;
  count: number | null;
  tone: string;
  /** A second, red badge when > 0: blocking and expired findings. */
  failing: number;
  note: HtmlValue;
  content: HtmlValue;
}

function chip(name: Parameters<typeof icon>[0], content: HtmlValue): SafeHtml {
  return html`<span class="chip">${icon(name)}${content}</span>`;
}

/** The app bar (09-REQ-17, item 1). */
function header(ctx: Ctx): SafeHtml {
  const r = ctx.report;
  const scope = r.scope.origins;
  return join(
    html`<header class="appbar"><div class="wrap">`,
    html`<p class="brand">${logo()}<b>${PACKAGE_NAME}</b> <span class="ver">v${r.pkgVersion}</span></p>`,
    html`<div class="meta" role="group" aria-label="Run details" tabindex="0">`,
    chip('play', html`mode <b>${r.mode}</b> · passive`),
    chip(
      'globe',
      scope.length === 0
        ? html`scope <b>none</b>`
        : html`scope <b>${scope[0]}</b>${scope.length > 1 ? ` +${String(scope.length - 1)}` : ''}`,
    ),
    chip(
      'clock',
      html`<b>${formatDate(r.startedAt).slice(0, -4)}</b> UTC · ${formatRunDuration(r.startedAt, r.finishedAt)}`,
    ),
    r.playwrightVersion === '' ? null : chip('env', html`Playwright <b>${r.playwrightVersion}</b>`),
    r.runId === ''
      ? null
      : html`<span class="chip mono"><span class="sr">Run ID </span>${r.runId}</span>`,
    html`</div></div></header>`,
  );
}

function tabs(ctx: Ctx): Tab[] {
  const r = ctx.report;
  const blocking = r.findings.filter(
    (f) => (f.classification === 'new' && f.blocking) || f.classification === 'expired',
  ).length;
  const issues = r.diagnostics.filter((d) => d.level !== 'info').length;
  return [
    {
      id: 'findings',
      label: 'Findings',
      count: r.findings.length,
      tone: '',
      failing: blocking,
      note: 'New blocking findings first, then expired, new non-blocking and baseline entries.',
      content: findingsTab(ctx),
    },
    {
      id: 'coverage',
      label: 'Coverage',
      count: null,
      tone: '',
      failing: 0,
      note: 'What the scan saw, and what it could not check.',
      content: coverageTab(ctx),
    },
    {
      id: 'run',
      label: 'Run & config',
      count: issues > 0 ? issues : null,
      tone: r.diagnostics.some((d) => d.level === 'error') ? 'bad' : 'warn',
      failing: 0,
      note: null,
      content: runTab(ctx),
    },
  ];
}

/** The tab bar; links to the panels without the script. */
function tabBar(list: readonly Tab[]): SafeHtml {
  return html`<nav class="tabs" aria-label="Report sections"><div class="seg" data-tabs="">${list.map(
    (t) =>
      html`<a href="#tab-${t.id}" id="tab-${t.id}-link" data-tab="${t.id}">${t.label}${t.count === null ? null : html` ${badge(t.count, t.tone)}`}${t.failing === 0 ? null : html` <span class="n bad">${t.failing}<span class="sr"> blocking or expired</span></span>`}</a>`,
  )}</div></nav>`;
}

function panel(t: Tab): SafeHtml {
  const quiet = t.note === null ? ' js-sr' : '';
  return html`<section class="panel" id="tab-${t.id}" data-panel="${t.id}" aria-labelledby="tab-${t.id}-h"><div class="ph${quiet}"><h2 id="tab-${t.id}-h">${t.label}</h2>${t.note === null ? null : html`<p>${t.note}</p>`}</div>${t.content}</section>`;
}

function footer(ctx: Ctx): SafeHtml {
  return html`<footer><div class="wrap">Generated by <a href="${REPOSITORY_URL}" rel="noopener noreferrer">${PACKAGE_NAME}</a> v${ctx.report.pkgVersion} · About this report: <code>${REPORTS_DOCS_URL}</code></div></footer>`;
}

/** Content-Security-Policy of the page, as in the perf report. */
export const CONTENT_SECURITY_POLICY = `default-src 'none'; script-src 'sha256-${SCRIPT_SHA256}'; style-src 'sha256-${STYLES_SHA256}'; img-src data:`;

/** The complete HTML report of a run (09, chapter 3). Pure and deterministic. */
export function renderHtmlReport(input: HtmlReportInput): string {
  const ctx = context(input);
  const r = ctx.report;
  const list = tabs(ctx);
  const head = join(
    html`<head><meta charset="utf-8">`,
    html`<meta http-equiv="Content-Security-Policy" content="${CONTENT_SECURITY_POLICY}">`,
    html`<meta name="viewport" content="width=device-width, initial-scale=1">`,
    html`<meta name="color-scheme" content="light dark">`,
    html`<meta name="generator" content="${`${PACKAGE_NAME} ${r.pkgVersion}`}">`,
    html`<link rel="icon" type="image/svg+xml" href="${FAVICON_URI}"><title>Security scan · ${r.outcome.name}${r.runId === '' ? '' : ` · ${r.runId}`}</title>`,
    html`<style>${trustedHtml(STYLES)}</style></head>`,
  );
  const main = join(
    html`<main id="main" class="wrap">`,
    verdictCard(ctx),
    kpis(ctx),
    tabBar(list),
    html`<p class="status-msg" id="status" role="status"></p>`,
    list.map(panel),
    html`</main>`,
  );
  const page = join(
    html`<!doctype html>\n<html lang="en">${head}\n<body><a class="skip" href="#main">Skip to content</a>`,
    iconSprite(),
    header(ctx),
    main,
    footer(ctx),
    html`\n<script>${trustedHtml(SCRIPT)}</script>\n</body></html>\n`,
  );
  return page.text;
}
