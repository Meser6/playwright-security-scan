const rule = (
  id: string,
  group: RuleGroup,
  title: string,
  defaultSeverity: Severity,
  defaultConfidence: Confidence,
  scope: FindingScope,
  cwe: number[],
  owasp: string | undefined,
  sources: Source[],
  options: Record<string, unknown> = {},
  strictOnly = false,
): RuleManifest => ({
  id,
  group,
  title,
  defaultSeverity,
  defaultConfidence,
  scope,
  cwe,
  ...(owasp === undefined ? {} : { owasp }),
  sources,
  options,
  ...(strictOnly ? { strictOnly } : {}),
});

