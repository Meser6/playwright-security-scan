// HTML escaping and the `html` tag of the report template (09-REQ-18): every interpolated value
// is escaped unless it is a SafeHtml produced by the template itself. Copied from
// playwright-performance-regression (src/html/escape.ts, MIT, D-08).

const SAFE: unique symbol = Symbol('SafeHtml');

/** Markup produced by the template; never built from report values without escaping. */
export interface SafeHtml {
  readonly [SAFE]: true;
  readonly text: string;
}

/** A value the `html` tag accepts: text is escaped, SafeHtml is kept, empty values vanish. */
export type HtmlValue =
  SafeHtml | string | number | null | undefined | false | readonly HtmlValue[];

const ESCAPES: Readonly<Record<string, string>> = {
  '&': '&amp;',
  '<': '&lt;',
  '>': '&gt;',
  '"': '&quot;',
  "'": '&#39;',
};

/** Escapes `&`, `<`, `>`, `"` and `'` for text and quoted attribute values (09-REQ-18). */
export function escapeHtml(value: string): string {
  return value.replace(/[&<>"']/gu, (c) => ESCAPES[c] ?? c);
}

function isSafe(value: unknown): value is SafeHtml {
  return typeof value === 'object' && value !== null && SAFE in value;
}

/**
 * Marks text as markup without escaping. Only for content generated by the template itself
 * (the embedded stylesheet and script, the JSON data element), never for report values.
 */
export function trustedHtml(text: string): SafeHtml {
  return { [SAFE]: true, text };
}

function render(value: HtmlValue): string {
  if (value === null || value === undefined || value === false) return '';
  if (typeof value === 'string') return escapeHtml(value);
  if (typeof value === 'number') return escapeHtml(String(value));
  if (isSafe(value)) return value.text;
  return (value as readonly HtmlValue[]).map(render).join('');
}

/** Tagged template that escapes every interpolated value by default (09-REQ-18). */
export function html(strings: TemplateStringsArray, ...values: HtmlValue[]): SafeHtml {
  let text = strings[0] ?? '';
  for (let i = 0; i < values.length; i++) {
    text += render(values[i]) + (strings[i + 1] ?? '');
  }
  return trustedHtml(text);
}
